// Shared terminology is aliased within each locale, never through an English fallback.
function withAliases(d: WikiLabels) {
  return {
    ...d,
    allKnowledge: d.allDocuments,
    documents: d.documentCount,
    unknownLanguage: d.languageUnknown,
    firstIndexed: d.firstObserved,
    indexChanged: d.indexUpdated,
    synced: d.lastSync,
    sourceOnlyNote: d.indexOnly,
    backToWiki: d.backToKnowledge,
    saveWiki: d.save,
    saveFailed: d.storageUnavailable,
    sourceMissing: d.missingDocument,
    sourceAmbiguous: d.ambiguous,
    sourceUnresolved: d.unresolved,
    topicFilter: d.topics,
    sourceEvidence: d.referenceEvidence,
  };
}

export type WikiDictionary = ReturnType<typeof withAliases>;
const dictionaries: Record<Locale, WikiDictionary> = {
  en: withAliases(labels.en), 'zh-CN': withAliases(labels['zh-CN']), 'zh-TW': withAliases(labels['zh-TW']),
  ja: withAliases(labels.ja), ko: withAliases(labels.ko), de: withAliases(labels.de),
  fr: withAliases(labels.fr), es: withAliases(labels.es), it: withAliases(labels.it), ru: withAliases(labels.ru),
};

export function getWikiDictionary(locale: Locale): WikiDictionary {
  return dictionaries[locale];
}
